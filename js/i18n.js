export const LANGS = ['ru', 'kk'];
export const HTML_LANG = { ru: 'ru', kk: 'kk' };

let current = 'ru';

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : 'ru';
  document.documentElement.lang = HTML_LANG[current];
}

export function getLang() {
  return current;
}

/** Строка интерфейса с подстановкой параметров {name}. */
export function t(key, params = {}) {
  const str = STRINGS[current][key] ?? STRINGS.ru[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`));
}

/** Локализованное значение контента вида { ru: '...', kk: '...' }. */
export function tr(obj) {
  if (!obj) return '';
  return obj[current] ?? obj.ru ?? '';
}

export function formatDate(ts) {
  const locale = current === 'kk' ? 'kk-KZ' : 'ru-RU';
  try {
    return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(ts));
  } catch {
    return new Date(ts).toLocaleString();
  }
}

export function formatDuration(sec) {
  const m = Math.floor(sec / 60);
  const s = Math.round(sec % 60);
  return `${m}:${String(s).padStart(2, '0')}`;
}

